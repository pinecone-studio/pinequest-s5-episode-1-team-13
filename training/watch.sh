#!/bin/bash
# Сургалтын явцыг терминалд шууд харуулна (5 сек тутам шинэчлэгдэнэ).
# ⌃C дарахад зөвхөн харахаа зогсооно, сургалт үргэлжилнэ.
DIR="$(cd "$(dirname "$0")" && pwd)"
while true; do
  printf '\033[H\033[2J'
  echo "=== МОДЕЛЬ СУРГАЛТ (⌃C = харахаа зогсоох; сургалт үргэлжилнэ) ==="
  python3 "$DIR/watch_status.py"
  sleep 5
done
